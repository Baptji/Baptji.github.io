const ACCENTS = {
  'É': ['E', ['...#.', '..#..']],
  'È': ['E', ['.#...', '..#..']],
  'Ê': ['E', ['..#..', '.#.#.']],
  'Ë': ['E', ['.#.#.', '.....']],
  'À': ['A', ['.#...', '..#..']],
  'Â': ['A', ['..#..', '.#.#.']],
  'Î': ['I', ['.#.', '#.#']],
  'Ï': ['I', ['#.#', '...']],
  'Ô': ['O', ['..#..', '.#.#.']],
  'Ù': ['U', ['.#...', '..#..']],
  'Û': ['U', ['..#..', '.#.#.']],
  'Ç': ['C', ['.....', '.....']],
};

function glyphe(c) {
  let m = c.toUpperCase();
  if ('−–—'.includes(c)) m = '-';
  if (ACCENTS[m] && CORPS[ACCENTS[m][0]]) {
    const b = CORPS[ACCENTS[m][0]].split('|');
    return { lignes: ACCENTS[m][1].map((l) => l.padEnd(b[0].length, '.')).concat(b), largeur: b[0].length };
  }
  const b = (CORPS[m] || CORPS['?']).split('|'), vide = '.'.repeat(b[0].length);
  return { lignes: [vide, vide].concat(b), largeur: b[0].length };
}
const avecAccents = (s) => [...s.toUpperCase()].some((c) => ACCENTS[c] && c !== 'Ç');

/// Un titre en police pixel, sous forme de <canvas> (taille d'un pixel en points CSS).
export function textePixel(texte, taille = 1.5, couleur = 'currentColor') {
  const accents = avecAccents(texte), haut = accents ? 0 : 2;
  const gs = [...texte].map(glyphe);
  const larg = gs.reduce((a, g) => a + g.largeur, 0) + Math.max(0, gs.length - 1);
  const lignes = accents ? 9 : 7;
  const dpr = window.devicePixelRatio || 1, k = taille * dpr;
  const cv = document.createElement('canvas');
  cv.width = Math.ceil(larg * k); cv.height = Math.ceil(lignes * k);
  cv.style.width = `${larg * taille}px`; cv.style.height = `${lignes * taille}px`;
  cv.className = 'pixel';
  const ctx = cv.getContext('2d');
  ctx.fillStyle = couleur === 'currentColor' ? getComputedStyle(document.documentElement).getPropertyValue('--texte-doux') || '#888' : couleur;
  let x = 0;
  for (const g of gs) {
    g.lignes.forEach((l, j) => {
      if (j < haut) return;
      for (let i = 0; i < l.length; i++) if (l[i] === '#') ctx.fillRect(Math.round((x + i) * k), Math.round((j - haut) * k), Math.ceil(k), Math.ceil(k));
    });
    x += g.largeur + 1;
  }
  cv.setAttribute('role', 'img'); cv.setAttribute('aria-label', texte);
  return cv;
}
